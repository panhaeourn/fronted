const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const translatedAttributes = ["placeholder", "title", "aria-label"];

function translateValue(value: string) {
  const trimmed = value.trim();
  const translated = khmerUi[trimmed];
  if (!translated) return value;
  const start = value.slice(0, value.indexOf(trimmed));
  const end = value.slice(value.indexOf(trimmed) + trimmed.length);
  return `${start}${translated}${end}`;
}

function shouldSkip(element: Element | null) {
  return !!element?.closest("script, style, code, pre, textarea, [data-no-translate]");
}

function translateTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const text = node as Text;
    if (!shouldSkip(text.parentElement)) {
      const source = originalText.get(text) ?? text.data;
      const translated = translateValue(source);
      if (translated !== source) {
        originalText.set(text, source);
        text.data = translated;
      }
    }
    node = walker.nextNode();
  }

  const elements = root instanceof Element ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  elements.forEach((element) => {
    if (shouldSkip(element)) return;
    translatedAttributes.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (!current) return;
      const saved = originalAttributes.get(element)?.get(attribute) ?? current;
      const translated = translateValue(saved);
      if (translated === saved) return;
      const attributes = originalAttributes.get(element) ?? new Map<string, string>();
      attributes.set(attribute, saved);
      originalAttributes.set(element, attributes);
      element.setAttribute(attribute, translated);
    });
  });
}

function restoreTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const text = node as Text;
    const source = originalText.get(text);
    if (source !== undefined) text.data = source;
    node = walker.nextNode();
  }
  const elements = root instanceof Element ? [root, ...root.querySelectorAll("*")] : [...root.querySelectorAll("*")];
  elements.forEach((element) => {
    originalAttributes.get(element)?.forEach((value, attribute) => element.setAttribute(attribute, value));
  });
}

export function applyKhmerInterface(root: ParentNode = document) {
  translateTree(root);
}

export function restoreEnglishInterface(root: ParentNode = document) {
  restoreTree(root);
}
